#!/usr/bin/env python3
"""Generate strongSwan swanctl.conf pairs for the IPsec configuration test matrix.

Each profile varies: IKE version / aggressive mode, IKE & ESP/AH proposals
(AES-128/256, AES-GCM, AES-CBC+HMAC, 3DES, NULL), DH group, PFS on/off,
tunnel vs transport mode, IPv4 vs IPv6 and rekey lifetimes.
"""
import os

PSK = os.environ.get("LAB_PSK", "0sLabOnly-Change-Me-7f3a9c1e2b")  # lab-only secret

PROFILES = {
    #  name                    ver aggr  ike proposal                     esp/ah proposal            mode        ipv  rekey
    "cnsa-suite-b":           (2, False, "aes256gcm16-prfsha384-ecp384", "esp=aes256gcm16-ecp384", "tunnel",    4, "45s"),
    "enterprise-default":     (2, False, "aes256-sha256-modp2048",       "esp=aes256-sha256-modp2048", "tunnel",  4, "40s"),
    "modern-ecp":             (2, False, "aes128gcm16-prfsha256-x25519", "esp=aes128gcm16-x25519", "tunnel",    4, "50s"),
    "aes128-cbc-nopfs":       (2, False, "aes128-sha256-modp2048",       "esp=aes128-sha256",       "tunnel",    4, "60s"),
    "host-to-host-transport": (2, False, "aes256-sha256-modp2048",       "esp=aes128-sha1",         "transport", 4, "1h"),
    "ipv6-tunnel":            (2, False, "aes256gcm16-prfsha256-ecp256", "esp=aes256gcm16-ecp256", "tunnel",    6, "40s"),
    "ipv6-transport":         (2, False, "aes256-sha256-ecp256",         "esp=aes256-sha256",       "transport", 6, "1h"),
    "legacy-ikev1-main":      (1, False, "3des-sha1-modp1024",           "esp=3des-sha1",           "tunnel",    4, "45s"),
    "insecure-aggressive-psk":(1, True,  "3des-md5-modp1024",            "esp=3des-md5",            "tunnel",    4, "24h"),
    "null-encryption":        (2, False, "aes128-sha256-modp1536",       "esp=null-sha1",           "tunnel",    4, "1h"),
    "ah-integrity-only":      (2, False, "aes256-sha256-modp2048",       "ah=sha256-modp2048",      "tunnel",    4, "1h"),
    "gcm-transport-pfs":      (2, False, "aes256gcm16-prfsha384-ecp384", "esp=aes256gcm16-ecp384", "transport", 4, "45s"),
}

ADDR = {4: {"a": "172.30.0.2", "b": "172.30.0.3", "net_a": "10.1.0.0/24", "net_b": "10.2.0.0/24"},
        6: {"a": "fd30::2", "b": "fd30::3", "net_a": "fd01::/64", "net_b": "fd02::/64"}}


def conf(me, peer, ver, aggr, ike, child, mode, ipv, rekey):
    a = ADDR[ipv]
    local_ts, remote_ts = (a[f"net_{me}"], a[f"net_{peer}"]) if mode == "tunnel" else ("dynamic", "dynamic")
    kind, prop = child.split("=")
    return f"""# generated by gen_profiles.py
connections {{
  lab {{
    version = {ver}
    aggressive = {'yes' if aggr else 'no'}
    local_addrs = {a[me]}
    remote_addrs = {a[peer]}
    proposals = {ike}
    rekey_time = 4h
    local {{ auth = psk
             id = gw-{me}.lab.example }}
    remote {{ auth = psk
              id = gw-{peer}.lab.example }}
    children {{
      net {{
        local_ts = {local_ts}
        remote_ts = {remote_ts}
        mode = {mode}
        {kind}_proposals = {prop}
        rekey_time = {rekey}
        replay_window = 32
        start_action = {'start' if me == 'a' else 'trap'}
      }}
    }}
  }}
}}
secrets {{
  ike-lab {{ id-a = gw-a.lab.example
             id-b = gw-b.lab.example
             secret = {PSK} }}
}}
"""


if __name__ == "__main__":
    base = os.path.join(os.path.dirname(os.path.abspath(__file__)), "profiles")
    for name, p in PROFILES.items():
        d = os.path.join(base, name)
        os.makedirs(d, exist_ok=True)
        for me, peer in (("a", "b"), ("b", "a")):
            with open(os.path.join(d, f"gw-{me}.swanctl.conf"), "w") as f:
                f.write(conf(me, peer, *p))
    print(f"wrote {len(PROFILES)} profiles to {base}")
